@dataclass(frozen=True)
class CPTCSpec:
    bits: int = 4
    trellis_depth: int = 16
    table_q: int = 6
    block_size: int = 128

    def __post_init__(self):
        for name in ("bits", "trellis_depth", "table_q", "block_size"):
            if type(getattr(self, name)) is not int:
                raise ValueError(f"CPTC `{name}` must be an integer")
        if not 1 <= self.bits <= 6:
            raise ValueError("CPTC `bits` must be in [1, 6]")
        if not self.bits <= self.trellis_depth <= 16:
            raise ValueError("CPTC `trellis_depth` must be between `bits` and 16")
        if not self.bits <= self.table_q <= 6:
            raise ValueError("CPTC `table_q` must be between `bits` and 6")
        if self.block_size not in (128, 256):
            raise ValueError("CPTC `block_size` must be 128 or 256")

    @property
    def block_bytes(self) -> int:
        return self.block_size * self.bits // 8

    @property
    def table_size(self) -> int:
        return 1 << self.table_q

    @property
    def shift(self) -> int:
        # The scalar embedding uses the first 2**L entries without folding.
        return 16 - min(self.table_q, self.trellis_depth)

    def blocks(self, in_features: int) -> int:
        return (in_features + self.block_size - 1) // self.block_size

    def coefficients(self, *, unified: bool = False) -> tuple[int, int]:
        if self.trellis_depth <= 6:
            return 0, _SCALAR_COEFFS[self.trellis_depth - 1]
        pair = _TRELLIS_COEFFS[self.trellis_depth - 7][-1 if unified else self.bits - 1]
        return pair >> 16, pair & 0xFFFF


def decode_e2m5(codes: torch.Tensor) -> torch.Tensor:
    """Decode all E2M5 values, including signed zeros and the reserved NaNs."""
    exponent = (codes.int() >> 5) & 3
    mantissa = codes & 31
    # In units of 1/32, subnormals are m and normal values are (32+m)*2**(e-1).
    units = torch.where(exponent == 0, mantissa, (mantissa.to(torch.int32) + 32) << (exponent - 1).clamp_min(0))
    value = units.float() * (1 / 32)
    value = torch.where((codes & 127) == 127, float("nan"), value)
    return torch.where(codes >= 128, -value, value)


def snap_e2m5(values: torch.Tensor) -> torch.Tensor:
    """Round to the closest finite code, with half-way ties to even."""
    grid = decode_e2m5(torch.arange(127, dtype=torch.uint8, device=values.device))
    magnitude = values.abs().contiguous()
    upper = torch.searchsorted(grid, magnitude).clamp(1, 126)
    lower = upper - 1
    midpoint = (grid[upper] + grid[lower]) * 0.5
    use_upper = (magnitude > midpoint) | ((magnitude == midpoint) & (upper % 2 == 0))
    return (torch.where(use_upper, upper, lower) | (values.signbit().to(torch.int64) << 7)).to(torch.uint8)


def state_indices(states: torch.Tensor, coeffs, shift: int) -> torch.Tensor:
    """Algorithm 1 before the mirrored codebook lookup."""
    state = states.to(torch.int64)
    first = ((state * coeffs[0]) & 0xFFFF) >> shift
    second = ((state * coeffs[1]) & 0xFFFF) >> shift
    return first + second


def _lookup(indices: torch.Tensor, table: torch.Tensor) -> torch.Tensor:
    mirrored = indices >= table.numel()
    indices = torch.where(mirrored, 2 * (table.numel() - 1) - indices, indices)
    return torch.where(mirrored, -table[indices], table[indices])


def unpack_states(packed: torch.Tensor, spec: CPTCSpec) -> torch.Tensor:
    """Algorithm 2, reading each little-endian window relative to its own block."""
    positions = torch.arange(spec.block_size, device=packed.device) * spec.bits
    byte, shift = positions // 8, positions % 8
    window = packed[..., byte].int()
    window |= packed[..., (byte + 1) % spec.block_bytes].int() << 8
    window |= packed[..., (byte + 2) % spec.block_bytes].int() << 16
    return (window >> shift) & ((1 << spec.trellis_depth) - 1)


def pack_states(states: torch.Tensor, spec: CPTCSpec) -> torch.Tensor:
    """Write the low K bits of each state into the byte stream."""
    # Each eight consecutive codes fill exactly K bytes. No scatter/atomics.
    codes = states.reshape(*states.shape[:-1], spec.block_size // 8, 8).long() & ((1 << spec.bits) - 1)
    code_shifts = torch.arange(8, device=states.device) * spec.bits
    byte_shifts = torch.arange(spec.bits, device=states.device) * 8
    words = (codes << code_shifts).sum(dim=-1, keepdim=True)
    return (words >> byte_shifts).to(torch.uint8).flatten(-2)


def decode_weight(packed, table, coeffs, scales, spec: CPTCSpec, in_features: int) -> torch.Tensor:
    states = unpack_states(packed, spec)
    indices = state_indices(states, coeffs, spec.shift)
    values = _lookup(indices, decode_e2m5(table)) * scales.float().unsqueeze(-1)
    return values.flatten(-2)[..., :in_features].contiguous()


def _viterbi_pass(blocks, decoded, spec, back, seam=None):
    """Minimize forward costs grouped by the high L-K bits of the window."""
    count, length = blocks.shape
    choices = 1 << spec.bits
    prefixes = 1 << (spec.trellis_depth - spec.bits)
    rows = torch.arange(count, device=blocks.device)
    cost = (blocks[:, :1] - decoded).square()
    if seam is not None:
        states = torch.arange(decoded.numel(), device=blocks.device)
        cost.masked_fill_(states != seam.unsqueeze(1), float("inf"))
    first = 0 if seam is not None else length // 2
    for step in range(length):
        best, low_bits = cost.reshape(count, prefixes, choices).min(dim=2)
        if step >= first:
            back[step].copy_(low_bits)
        if step + 1 < length:
            error = (blocks[:, step + 1:step + 2] - decoded).square()
            cost = (error.view(count, choices, prefixes) + best[:, None, :]).view(count, -1)
    prefix = best.argmin(dim=1) if seam is None else seam & (prefixes - 1)
    if seam is not None:
        path = torch.empty_like(blocks, dtype=torch.int32)
    for step in range(length - 1, first - 1, -1):
        state = (prefix << spec.bits) | back[step, rows, prefix].long()
        prefix = state & (prefixes - 1)
        if seam is not None:
            path[:, step] = state
    return path if seam is not None else state


def _viterbi_reference(blocks, decoded, spec):
    prefixes = 1 << (spec.trellis_depth - spec.bits)
    back = torch.empty((spec.block_size, blocks.shape[0], prefixes), dtype=torch.uint8, device=blocks.device)
    seam = _viterbi_pass(blocks.roll(spec.block_size // 2, dims=1), decoded, spec, back)
    return _viterbi_pass(blocks, decoded, spec, back, seam=seam)


def _encode_batch_size(spec: CPTCSpec) -> int:
    per_block = spec.block_size * (1 << (spec.trellis_depth - spec.bits)) + 12 * (1 << spec.trellis_depth)
    return min(4096, max(1, _SCRATCH_BYTES // per_block))


def viterbi_encode(blocks: torch.Tensor, decoded: torch.Tensor, spec: CPTCSpec, *, native=None) -> torch.Tensor:
    """Run the two-pass tail-biting search and return its L-bit windows."""
    if blocks.ndim != 2 or blocks.shape[1] != spec.block_size or decoded.shape != (1 << spec.trellis_depth,):
        raise ValueError("CPTC Viterbi input geometry does not match the spec")
    if blocks.shape[0] == 0:
        return torch.empty_like(blocks, dtype=torch.int32)
    paths = []
    for chunk in blocks.split(_encode_batch_size(spec)):
        if spec.trellis_depth == spec.bits:
            # No carry bits link successive symbols. Avoid adding a running
            # cost that can erase the difference between adjacent values.
            paths.append((chunk.float().unsqueeze(-1) - decoded).abs().argmin(dim=-1).int())
        elif native is None:
            paths.append(_viterbi_reference(chunk.float(), decoded, spec))
        else:
            paths.append(native.encode(chunk.float().contiguous(), decoded.contiguous(), spec.bits))
    return torch.cat(paths, dim=0)


def _starting_table(spec, indices):
    counts = torch.bincount(indices, minlength=2 * spec.table_size - 1).double()
    cdf = counts.cumsum(0) / indices.numel()
    edges = torch.cat((cdf.new_zeros(1), cdf))
    quantiles = math.sqrt(2) * torch.erfinv(2 * edges - 1)
    density = (-0.5 * quantiles.square()).exp() / math.sqrt(2 * math.pi)
    means = (density[:-1] - density[1:]) * indices.numel() / counts.clamp_min(1)
    if spec.trellis_depth > 6:
        means = (means - means.flip(0)) * 0.5
    width = math.sqrt((1 + 2 / (spec.trellis_depth - spec.bits + 1)) * (1 - 4.0**(-spec.bits)))
    return (means[:spec.table_size] * (width * _TABLE_STORAGE_SCALE)).float()


def _indices(spec: CPTCSpec, device) -> torch.Tensor:
    return state_indices(torch.arange(1 << spec.trellis_depth, device=device), spec.coefficients(), spec.shift)


@torch.no_grad()
def fit_gaussian_table(
    spec: CPTCSpec,
    *,
    device: torch.device | str,
    sample_blocks: int = 2048,
    rounds: int = 50,
    seed: int = 0,
) -> torch.Tensor:
    """Fit an E2M5 codebook with damped Lloyd updates and held-out selection."""
    from ..utils.cptc import native_ops

    if sample_blocks < 1 or rounds < 0:
        raise ValueError("CPTC table fitting needs positive sample_blocks and nonnegative rounds")
    device = torch.device(device)
    indices = _indices(spec, device)
    table = _starting_table(spec, indices)
    native = native_ops(device)
    rng = torch.Generator(device=device).manual_seed(seed)
    validation = torch.randn((512, spec.block_size), generator=rng, device=device) * _TABLE_STORAGE_SCALE
    best_loss = math.inf
    best = snap_e2m5(table)
    for step in range(rounds + 1):
        if step % 5 == 0 or step == rounds:
            candidate = snap_e2m5(table)
            decoded = _lookup(indices, decode_e2m5(candidate))
            states = viterbi_encode(validation, decoded, spec, native=native)
            loss = (decoded[states.long()] - validation).square().mean().item()
            if loss < best_loss:
                best_loss, best = loss, candidate
        if step == rounds:
            break
        samples = torch.randn((sample_blocks, spec.block_size), generator=rng, device=device) * _TABLE_STORAGE_SCALE
        states = viterbi_encode(samples, _lookup(indices, table), spec, native=native)
        cells = indices[states.long()].flatten()
        mirrored = cells >= spec.table_size
        cells = torch.where(mirrored, 2 * (spec.table_size - 1) - cells, cells)
        targets = torch.where(mirrored, -samples.flatten(), samples.flatten())
        counts = torch.bincount(cells, minlength=spec.table_size)
        sums = torch.bincount(cells, weights=targets, minlength=spec.table_size)
        means = torch.where(counts > 0, sums / counts.clamp_min(1), table)
        if spec.trellis_depth > 6:
            means[-1] = 0
        table = table.lerp(means, 0.5 if step < 30 else 0.25)
    return best


def gaussian_table(spec: CPTCSpec, device) -> torch.Tensor:
    """Get the codebook for direct packing without calibration samples."""
    if spec.trellis_depth == 16 and spec.table_q == 6:
        codes = bytes.fromhex(_GAUSSIAN_Q6_L16[spec.bits - 1])
        return torch.tensor(list(codes), dtype=torch.uint8, device=device)
    return snap_e2m5(_starting_table(spec, _indices(spec, "cpu"))).to(device)


@torch.no_grad()
def quantize_weight(weight: torch.Tensor, spec: CPTCSpec, *, device: torch.device, table=None):
    """Encode a weight matrix and return row-major packed blocks and FP32 scales."""
    from ..utils.cptc import native_ops

    if weight.ndim != 2 or not weight.is_floating_point() or min(weight.shape) < 1:
        raise ValueError("CPTC requires a nonempty floating-point weight matrix")
    out_features, in_features = weight.shape
    blocks_per_row = spec.blocks(in_features)
    coeffs = torch.tensor(spec.coefficients(), dtype=torch.int32, device=weight.device)
    table = gaussian_table(spec, device) if table is None else table.to(device)
    if table.dtype != torch.uint8 or table.shape != (spec.table_size,) or bool(((table & 127) == 127).any()):
        raise ValueError("CPTC requires a finite E2M5 table with 2**table_q entries")
    decoded = _lookup(_indices(spec, device), decode_e2m5(table))
    native = native_ops(device)
    if native is not None and spec.trellis_depth == 16:
        decoded = decoded.half()  # Exact E2M5 values for the register-cached GPU encoder.
    packed = torch.empty((out_features, blocks_per_row, spec.block_bytes), dtype=torch.uint8, device=weight.device)
    scales = torch.empty((out_features, blocks_per_row), dtype=torch.float32, device=weight.device)
    batch_size = _encode_batch_size(spec)
    padding = blocks_per_row * spec.block_size - in_features
    counts = torch.full((blocks_per_row,), spec.block_size, device=device, dtype=torch.float32)
    counts[-1] -= padding
    invalid = torch.zeros((), device=device, dtype=torch.bool)
    rows_per_batch = max(1, batch_size // blocks_per_row)
    for start in range(0, out_features, rows_per_batch):
        end = min(start + rows_per_batch, out_features)
        rows = weight[start:end].to(device=device, dtype=torch.float32)
        blocks = torch.nn.functional.pad(rows, (0, padding)).view(-1, blocks_per_row, spec.block_size)
        maximum = blocks.abs().amax(dim=-1)
        invalid |= ~torch.isfinite(maximum).all()
        normalized = blocks / torch.where(maximum > 0, maximum, 1).unsqueeze(-1)
        rms = (normalized.square().sum(dim=-1) / counts).sqrt() * maximum
        scale = (rms / _TABLE_STORAGE_SCALE).clamp_max(torch.finfo(torch.float32).max / 8)
        targets = (blocks / torch.where(scale > 0, scale, 1).unsqueeze(-1)).flatten(0, 1)
        # Cost arithmetic is FP32. Clipping very large normalized values to
        # a finite cost range only affects source weights outside FP32 range.
        targets = torch.nan_to_num(targets, nan=0, posinf=2048, neginf=-2048).clamp(-2048, 2048)
        path = viterbi_encode(targets, decoded, spec, native=native)
        packed[start:end].copy_(pack_states(path, spec).view(-1, blocks_per_row, spec.block_bytes))
        scales[start:end].copy_(scale)
    if bool(invalid):
        raise ValueError("CPTC cannot encode non-finite weights")
    return packed, table.to(weight.device).contiguous(), coeffs, scales
