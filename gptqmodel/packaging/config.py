"""Public configuration objects for the packaging API."""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import Any, Mapping


#: Dense (non-packed) tensor encodings a GGUF container may store.
DENSE_DTYPES = ("auto", "f16", "bf16", "f32")


def _existing_directory(value: Any, *, field_name: str) -> str:
    if not isinstance(value, (str, os.PathLike)) or not os.fspath(value):
        raise TypeError(f"PackageConfig: `{field_name}` must be a path, got {value!r}.")
    path = os.path.abspath(os.fspath(value))
    if not os.path.isdir(path):
        raise NotADirectoryError(f"PackageConfig: `{field_name}` must be an existing directory, got {path!r}.")
    return path


def _output_file(value: Any) -> str:
    if not isinstance(value, (str, os.PathLike)) or not os.fspath(value):
        raise TypeError(f"PackageConfig: `out_path` must be a path, got {value!r}.")
    path = os.path.abspath(os.fspath(value))
    if os.path.isdir(path):
        raise IsADirectoryError(
            f"PackageConfig: `out_path` must be a file path, got the directory {path!r}. "
            "Pass the `.gguf` file to write."
        )
    return path


@dataclass
class PackageConfig:
    """Where a packaging run reads a checkpoint and writes one container file.

    Subclasses select the target container and add its options; :func:`package`
    dispatches on the concrete type and rejects a type it has no writer for
    instead of guessing a format.
    """

    model_path: str = ""
    out_path: str = ""
    overwrite: bool = False

    def __post_init__(self) -> None:
        self.model_path = _existing_directory(self.model_path, field_name="model_path")
        self.out_path = _output_file(self.out_path)
        if type(self.overwrite) is not bool:
            raise TypeError(f"PackageConfig: `overwrite` must be a bool, got {type(self.overwrite).__name__}.")


@dataclass
class GGUFPackageConfig(PackageConfig):
    """Options for writing a llama.cpp/ggml single-file ``.gguf`` container.

    The source must be a GPT-QModel GGUF checkpoint (``quant_method``
    ``gptqmodel_gguf``): every linear already stores ggml block bytes in its
    ``qweight`` buffer, so this writer only renames, reorders whole output rows,
    and stores dense tensors. It never dequantizes or re-quantizes a weight.
    """

    #: Directory holding ``tokenizer.json``/``tokenizer_config.json``. Defaults
    #: to ``model_path``.
    tokenizer_path: str = ""
    #: An already loaded tokenizer object; takes precedence over
    #: ``tokenizer_path``. The writer never downloads or executes checkpoint code.
    tokenizer: Any = None
    #: Override the GGUF ``general.architecture`` derived from ``model_type``.
    architecture: str = ""
    #: Override the ``tokenizer.ggml.pre`` pre-tokenizer name.
    tokenizer_pre: str = ""
    #: Encoding for dense 2-D tensors. ``auto`` keeps the source width
    #: (BF16/F16/F32). 1-D tensors and norms are always F32.
    dense_dtype: str = "auto"
    #: ``general.name``. Defaults to the source directory name.
    name: str = ""
    #: Override the derived ``general.file_type`` (a ``LlamaFileType`` value).
    file_type: int = -1
    #: Tensor-data alignment in bytes. Must be a power of two.
    alignment: int = 32
    #: Override the tokenizer chat template.
    chat_template: str = ""
    #: Extra GGUF metadata. Keys already generated by the writer are reserved.
    metadata: Mapping[str, Any] = field(default_factory=dict)
    #: Use the generic name map and metadata for an architecture without a
    #: registered layout. No weight transform is applied, so a layout that
    #: needs one is written incorrectly; the default refuses instead.
    allow_unverified_arch: bool = False

    def __post_init__(self) -> None:
        super().__post_init__()
        if self.tokenizer_path:
            self.tokenizer_path = _existing_directory(self.tokenizer_path, field_name="tokenizer_path")
        if self.architecture and (not isinstance(self.architecture, str) or not self.architecture.strip()):
            raise ValueError("GGUFPackageConfig: `architecture` must be a non-empty string when set.")
        if self.tokenizer_pre and (not isinstance(self.tokenizer_pre, str) or not self.tokenizer_pre.strip()):
            raise ValueError("GGUFPackageConfig: `tokenizer_pre` must be a non-empty string when set.")
        if self.dense_dtype not in DENSE_DTYPES:
            raise ValueError(
                f"GGUFPackageConfig: `dense_dtype` must be one of {list(DENSE_DTYPES)}, got {self.dense_dtype!r}."
            )
        if self.name and (not isinstance(self.name, str) or not self.name.strip()):
            raise ValueError("GGUFPackageConfig: `name` must be a non-empty string when set.")
        if type(self.file_type) is not int or self.file_type < -1:
            raise TypeError(f"GGUFPackageConfig: `file_type` must be an int >= -1, got {self.file_type!r}.")
        if type(self.alignment) is not int or self.alignment < 1 or (self.alignment & (self.alignment - 1)) != 0:
            raise ValueError(
                f"GGUFPackageConfig: `alignment` must be a power of two >= 1, got {self.alignment!r}."
            )
        if self.chat_template and not isinstance(self.chat_template, str):
            raise TypeError("GGUFPackageConfig: `chat_template` must be a string when set.")
        if self.metadata is None:
            self.metadata = {}
        if not isinstance(self.metadata, Mapping):
            raise TypeError("GGUFPackageConfig: `metadata` must be a mapping.")
        for key, value in self.metadata.items():
            if not isinstance(key, str) or not key:
                raise TypeError(f"GGUFPackageConfig: metadata keys must be non-empty strings, got {key!r}.")
            if not isinstance(value, (str, bool, int, float)):
                raise TypeError(
                    f"GGUFPackageConfig: metadata value for `{key}` must be a str, bool, int or float, "
                    f"got {type(value).__name__}."
                )
        if type(self.allow_unverified_arch) is not bool:
            raise TypeError(
                f"GGUFPackageConfig: `allow_unverified_arch` must be a bool, got "
                f"{type(self.allow_unverified_arch).__name__}."
            )


__all__ = ["DENSE_DTYPES", "GGUFPackageConfig", "PackageConfig"]
