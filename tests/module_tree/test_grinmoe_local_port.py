import hashlib

import pytest
import torch

from gptqmodel.looper.module_looper import ModuleLooper
from gptqmodel.models.auto import MODEL_MAP
from gptqmodel.models.definitions.grinmoe import GrinMoeQModel
from gptqmodel.models.loader import _convert_model_with_defuser
from gptqmodel.models.ports.grinmoe.configuration_grinmoe import GRINMoEConfig
from gptqmodel.quantization import QuantizeConfig
from tests.test_grinmoe_local_port import tiny_config


@pytest.mark.parametrize("device", ["cpu", "meta"])
@pytest.mark.parametrize("bias,kv_heads,experts", [(True, 1, 2), (False, 2, 3), (True, 4, 4)])
def test_actual_checkpoint_owners_plan_roles_lifecycle_and_looper(device, bias, kv_heads, experts):
    config = tiny_config(attention_bias=bias, lm_head_bias=bias, num_key_value_heads=kv_heads,
                         num_local_experts=experts)
    with torch.device(device):
        model = GrinMoeQModel.loader.from_config(config)
    _convert_model_with_defuser(GrinMoeQModel, model, cleanup_original=False)
    qcfg = QuantizeConfig(group_size=8, offload_to_disk=False)
    wrapper = GrinMoeQModel(model=model, quantized=False, quantize_config=qcfg)
    assert MODEL_MAP["grinmoe"] is GrinMoeQModel
    assert {k for k, v in MODEL_MAP.items() if v is GrinMoeQModel} == {"grinmoe"}
    plan = wrapper.module_plan()
    expected_quantized = {f"self_attn.{name}_proj" for name in ("q", "k", "v", "o")}
    expected_quantized |= {f"block_sparse_moe.experts.{i}.{name}" for i in range(experts)
                           for name in ("w1", "w3", "w2")}
    expected_nonquantized = {"input_layernorm", "post_attention_layernorm", "block_sparse_moe.gate"}
    declared = {name for block in wrapper.simple_layer_modules(config, qcfg) for name in block}
    assert declared == expected_quantized
    awq_declared = {name for block in wrapper.simple_layer_modules(config, qcfg, is_awq_quantize=True)
                    for name in block}
    assert awq_declared == expected_quantized
    for layer in model.model.layers:
        owners = {key.rsplit(".", 1)[0] for key in layer.state_dict()}
        assert owners == expected_quantized | expected_nonquantized
        for owner in owners:
            spec = plan.find(owner)
            assert spec is not None and spec.template.count(".") == owner.count(".")
            assert spec.quantize == (owner in expected_quantized)
            if not spec.quantize:
                assert "!" in spec.flags
        hooks = wrapper.moe_lifecycle_hooks
        block = hooks.get_moe_block(layer, wrapper)
        assert block is layer.block_sparse_moe
        assert hooks.get_experts_module(block, wrapper) is block.experts
        assert hooks.gate_proj_name == "w1" and hooks.up_proj_name == "w3" and hooks.down_proj_name == "w2"
    for path, role in (("self_attn.q_proj", "q"), ("self_attn.k_proj", "k"),
                       ("self_attn.v_proj", "v"), ("self_attn.o_proj", "o"),
                       ("block_sparse_moe.experts.0.w1", "gate"),
                       ("block_sparse_moe.experts.0.w3", "up"),
                       (f"block_sparse_moe.experts.{experts - 1}.w2", "down")):
        assert plan.find(path).roles == (role,)
    assert plan.find("block_sparse_moe.gate").quantize is False
    assert plan.find("block_sparse_moe.experts.0.w1.undeclared") is None
    assert plan.find("pretend_self_attn.q_proj") is None
    assert plan.find("block_sparse_moe.experts_extra.0.w1") is None
    looper = ModuleLooper.__new__(ModuleLooper)
    looper.gptq_model = wrapper
    assert looper._extract_moe_group_key("block_sparse_moe.experts.0.w1") == "block_sparse_moe.experts.0"
    assert looper._extract_moe_group_key("self_attn.q_proj") is None
    assert wrapper.awq_get_modules_for_scaling(model.model.layers[0], {}, {}) == []


def test_exact_published_checkpoint_key_inventory_on_real_meta_model():
    # Pinned Microsoft checkpoint index, not an inventory generated by ModulePlan.
    config = GRINMoEConfig(
        vocab_size=32064, hidden_size=4096, intermediate_size=6400, num_hidden_layers=32,
        num_attention_heads=32, num_key_value_heads=8, num_local_experts=16,
        max_position_embeddings=4096, rope_theta=10000.0, sliding_window=2047,
        attention_bias=True, lm_head_bias=True,
    )
    with torch.device("meta"):
        model = GrinMoeQModel.loader.from_config(config)
    keys = sorted(model.state_dict())
    assert len(keys) == 1957
    assert hashlib.sha256("\n".join(keys).encode()).hexdigest() == CHECKPOINT_KEYS_SHA256
    state = model.state_dict()
    assert state["model.layers.0.self_attn.q_proj.weight"].shape == (4096, 4096)
    assert state["model.layers.0.self_attn.k_proj.weight"].shape == (1024, 4096)
    assert state["model.layers.31.block_sparse_moe.experts.15.w1.weight"].shape == (6400, 4096)
    assert state["model.layers.31.block_sparse_moe.experts.15.w2.weight"].shape == (4096, 6400)
    assert state["lm_head.bias"].shape == (32064,)
    assert all(value.device.type == "meta" for value in state.values())


CHECKPOINT_KEYS_SHA256 = "cb4174bff210a863ec9a8ff743a76ea0644028479518382eef6a5ad8347e2675"
